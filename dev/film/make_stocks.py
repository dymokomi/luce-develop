#!/usr/bin/env python3
"""Write src/film_stocks.lucb: each film stock's published curves resampled for the
film model (src/film.lucb). Edit or add a stock's digitized data here, then run
dev/film/make_stocks.py.

Kodak EXR 500T 5298 comes from Kodak's own datasheet (TI2082, revised 10-93), read
off its graphs by digitize_ti2082.py into kodak_5298_ti2082.json. The sheet has no
per-dye spectra, so the dye shapes are EXR 200T 5293's (H-1-5293t), the same ECN-2
dye set, read exactly from that PDF's vector paths (kodak_5293_dyes.json)."""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
NM = [380.0 + 5.0 * i for i in range(81)]


def interp(xs, ys, q):
    """Linear interpolation; None outside."""
    if q < xs[0] or q > xs[-1]:
        return None
    for (a, ya), (b, yb) in zip(zip(xs, ys), zip(xs[1:], ys[1:])):
        if a <= q <= b:
            return ya if b == a else ya + (yb - ya) * (q - a) / (b - a)
    return ys[-1]


def column(table, axis, name):
    pairs = [(x, y) for x, y in zip(table[axis], table[name]) if y is not None]
    return [p[0] for p in pairs], [p[1] for p in pairs]


def log_sensitivity(table, name, first=None, first_value=None):
    xs, ys = column(table, 'nm', name)
    if first is not None:
        xs, ys = [first] + xs, [first_value] + ys
    out = []
    for q in NM:
        v = interp(xs, ys, q)
        if v is None:
            # Beyond what Kodak plots, sensitivity falls away steeply (0.12 log per nm).
            v = ys[0] - 0.12 * (xs[0] - q) if q < xs[0] else ys[-1] - 0.12 * (q - xs[-1])
        out.append(v)
    return out


def spectral(table, name):
    xs, ys = column(table, 'nm', name)
    # The graph runs 400–700 nm; hold the ends flat beyond it.
    return [interp(xs, ys, min(max(q, xs[0]), xs[-1])) for q in NM]


def dye(points):
    xs = [p[0] for p in points]; ys = [p[1] for p in points]
    return [max(0.0, interp(xs, ys, min(max(q, xs[0]), xs[-1]))) for q in NM]


def number(v):
    t = ('%.5f' % v).rstrip('0')
    return t + '0' if t.endswith('.') else t


def block(values, per_line=12, indent='        '):
    lines = [', '.join(number(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return '[\n' + ',\n'.join(indent + line for line in lines) + ']'


sheet = json.load(open(here / 'kodak_5298_ti2082.json'))
dyes = json.load(open(here / 'kodak_5293_dyes.json'))

sensitivity = (log_sensitivity(sheet['sensitivity'], 'red') + log_sensitivity(sheet['sensitivity'], 'olive')
               # The blue curve starts at 400 nm on the graph (2.65); the digitizer's first reading is 405.
               + log_sensitivity(sheet['sensitivity'], 'blue', 400.0, 2.65))
dye_densities = dye(dyes['cyan']) + dye(dyes['magenta']) + dye(dyes['yellow'])
neutral = spectral(sheet['dye_density'], 'blue')
d_min = spectral(sheet['dye_density'], 'olive')
char = sheet['characteristic']
curves = []
for name in ('red', 'olive', 'blue'):
    xs, ys = column(char, 'log_h', name)
    curves += [interp(xs, ys, q) for q in char['log_h']]
grain = sheet['granularity']
# Readings where all three layers were read.
grain_log_h = [q for i, q in enumerate(grain['log_h']) if all(grain[n][i] is not None for n in ('red', 'olive', 'blue'))]
granularity = []
for name in ('red', 'olive', 'blue'):
    xs, ys = column(grain, 'log_h', name)
    granularity += [interp(xs, ys, q) for q in grain_log_h]
mtf = sheet['mtf']
# Kodak's curves start at about 2.5 cycles per mm; the first full reading is at 3.
frequencies = [f for f in mtf['cycles_per_mm'] if f >= 3]
responses = []
for name in ('red', 'olive', 'blue'):
    xs, ys = column(mtf, 'cycles_per_mm', name)
    # The last reading Kodak plots is at 100 c/mm; the digitizer stops at 90: continue the slope.
    responses += [interp(xs, ys, q) if q <= xs[-1] else ys[-1] + (ys[-1] - ys[-2]) / (xs[-1] - xs[-2]) * (q - xs[-1]) for q in frequencies]

assert len(char['log_h']) == 59 and len(grain_log_h) == 29 and len(frequencies) == 18
assert all(v is not None for v in curves + granularity + responses)

out = f'''## Generated by dev/film/make_stocks.py; do not edit. The film stocks the film
## model (film.lucb) develops: each one's published curves, resampled. Spectra are
## at spectral.samples (380–780 nm every 5 nm); per-layer tables are red, green,
## blue (cyan-, magenta-, yellow-forming) one after another.
from luce_color import spectral

## A color negative stock as its datasheet describes it.
pub struct Stock:
    pub var name: str
    ## The light it is balanced for, in kelvin.
    pub var kelvin: f64
    ## log10 spectral sensitivity per layer (reciprocal exposure for a fixed density).
    pub var sensitivity: f64[243]
    ## Peak-normalized spectral density of the cyan, magenta and yellow dyes.
    pub var dyes: f64[243]
    ## Diffuse spectral density at minimum density (base, fog and the colored-coupler mask).
    pub var d_min: f64[81]
    ## Diffuse spectral density of a midscale neutral.
    pub var neutral: f64[81]
    ## Status M density per layer over log exposure (lux s), 59 readings from
    ## `curve_first` every `curve_step`.
    pub var curve_first: f64
    pub var curve_step: f64
    pub var curves: f64[177]
    ## Diffuse rms granularity (σD through a 48 µm aperture) per layer over log
    ## exposure, 29 readings from `granularity_first` every `granularity_step`.
    pub var granularity_first: f64
    pub var granularity_step: f64
    pub var granularity: f64[87]
    ## Modulation transfer (percent) per layer at `mtf_frequencies` (cycles per mm).
    pub var mtf_frequencies: f64[18]
    pub var mtf: f64[54]

## Kodak EXR 500T 5298 (1993): Kodak TI2082, with EXR 200T 5293's dye shapes.
pub func kodak_5298() -> Stock:
    return Stock(
        name = "Kodak EXR 500T 5298",
        kelvin = 3200.0,
        sensitivity = {block(sensitivity)},
        dyes = {block(dye_densities)},
        d_min = {block(d_min)},
        neutral = {block(neutral)},
        curve_first = {number(char['log_h'][0])},
        curve_step = 0.05,
        curves = {block(curves)},
        granularity_first = {number(grain_log_h[0])},
        granularity_step = 0.1,
        granularity = {block(granularity)},
        mtf_frequencies = {block([float(f) for f in frequencies])},
        mtf = {block(responses)})
'''
(here.parents[1] / 'src/film_stocks.lucb').write_text(out)
print('wrote src/film_stocks.lucb')
